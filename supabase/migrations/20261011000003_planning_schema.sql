  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  statement_day smallint not null check (statement_day between 1 and 31),
  due_day smallint not null check (due_day between 1 and 31),
  credit_limit_centavos bigint check (credit_limit_centavos > 0),
  monthly_interest_bps integer not null check (monthly_interest_bps between 0 and 1000),
  min_payment_bps integer not null check (min_payment_bps between 0 and 10000),
  min_payment_floor_centavos bigint not null default 0 check (min_payment_floor_centavos >= 0),
