-- recurring rules use the same shared-or-own category check as transactions
create or replace function public.assert_visible_refs()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_table_name = 'accounts' then
    if not exists (
      select 1 from public.institutions i
      where i.id = new.institution_id and (i.user_id is null or i.user_id = new.user_id)
    ) then
      raise exception 'institution % not found', new.institution_id using errcode = '23503';
    end if;
  elsif tg_table_name in ('transactions', 'recurring_rules') and new.category_id is not null then
    if not exists (
      select 1 from public.categories c
      where c.id = new.category_id and (c.user_id is null or c.user_id = new.user_id)
    ) then
      raise exception 'category % not found', new.category_id using errcode = '23503';
    end if;
  end if;
  return new;
end;
$$;
create trigger recurring_rules_visible_refs before insert or update on public.recurring_rules
  for each row execute function public.assert_visible_refs();

