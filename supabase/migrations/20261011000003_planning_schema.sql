  for each row execute function public.assert_account_type('{loan}');

create table public.loan_payments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  loan_id uuid not null,
  seq smallint not null check (seq >= 1),
  due_date date not null,
  principal_centavos bigint not null check (principal_centavos >= 0),
  interest_centavos bigint not null check (interest_centavos >= 0),
  amount_centavos bigint generated always as (principal_centavos + interest_centavos) stored,
  paid_at timestamptz,
  transaction_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (loan_id, seq),
  foreign key (loan_id, user_id) references public.loans (id, user_id) on delete cascade,
  foreign key (transaction_id, user_id) references public.transactions (id, user_id) on delete set null (transaction_id)
);
create index loan_payments_user_due_idx on public.loan_payments (user_id, due_date);
create index loan_payments_transaction_id_idx on public.loan_payments (transaction_id);

create function public.build_loan_schedule()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  r numeric := new.monthly_rate_bps::numeric / 10000;
  n integer := new.term_months;
  bal bigint := new.principal_centavos;
  pmt bigint;
  total_interest bigint;
  principal bigint;
  interest bigint;
begin
  if tg_op = 'UPDATE' then
    if (new.principal_centavos, new.monthly_rate_bps, new.interest_method, new.term_months,
        new.first_due_date, new.payment_centavos)
       is not distinct from
       (old.principal_centavos, old.monthly_rate_bps, old.interest_method, old.term_months,
        old.first_due_date, old.payment_centavos) then
      return new;
    end if;
    if exists (select 1 from public.loan_payments p where p.loan_id = new.id and p.paid_at is not null) then
      raise exception 'loan terms cannot change after a payment is recorded' using errcode = '23514';
    end if;
    delete from public.loan_payments p where p.loan_id = new.id;
  end if;

  if new.interest_method = 'add_on' then
    -- Flat rate on the original principal for the whole term, spread evenly; last row takes rounding.
    total_interest := round(new.principal_centavos * r * n);
    for k in 1..n loop
      if k < n then
        principal := new.principal_centavos / n;
        interest := total_interest / n;
      else
        principal := new.principal_centavos - (new.principal_centavos / n) * (n - 1);
        interest := total_interest - (total_interest / n) * (n - 1);
      end if;
      insert into public.loan_payments (user_id, loan_id, seq, due_date, principal_centavos, interest_centavos)
      values (new.user_id, new.id, k, (new.first_due_date + make_interval(months => k - 1))::date, principal, interest);
    end loop;
  else
    -- Diminishing balance: interest on the remaining balance; last row clears the balance.
    pmt := coalesce(
      new.payment_centavos,
      case when r = 0 then ceil(new.principal_centavos::numeric / n)
           else round(new.principal_centavos * r / (1 - power(1 + r, -n))) end
    );
    for k in 1..n loop
      interest := round(bal * r);
      if k < n then
        principal := pmt - interest;
        if principal <= 0 then
          raise exception 'payment % does not cover interest % in month %', pmt, interest, k using errcode = '23514';
        end if;
        principal := least(principal, bal);
      else
        principal := bal;
      end if;
      insert into public.loan_payments (user_id, loan_id, seq, due_date, principal_centavos, interest_centavos)
      values (new.user_id, new.id, k, (new.first_due_date + make_interval(months => k - 1))::date, principal, interest);
      bal := bal - principal;
      exit when bal = 0;
    end loop;
  end if;
  return new;
end;
$$;

create trigger loans_build_schedule after insert or update on public.loans
  for each row execute function public.build_loan_schedule();

