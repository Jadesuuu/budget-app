-- Planning schema: credit cards, statements, loans (+ schedule), installment plans (+ schedule),
-- income sources, recurring rules. Rates are integer basis points (300 = 3.00%); dates that are
-- calendar days in Asia/Manila (due dates, statement dates) are `date`, instants are timestamptz.

create type public.interest_method as enum ('diminishing', 'add_on');
create type public.pay_frequency as enum ('weekly', 'biweekly', 'semi_monthly', 'monthly', 'quarterly', 'yearly');
create type public.installment_frequency as enum ('monthly', 'biweekly');

-- Child rows may only attach to an own account of the given type(s): tg_argv[0] = '{credit}' etc.
create function public.assert_account_type()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  allowed public.account_type[] := tg_argv[0]::public.account_type[];
  found_type public.account_type;
begin
  select a.type into found_type
    from public.accounts a
   where a.id = new.account_id and a.user_id = new.user_id;
  if found_type is null then
    raise exception 'account % not found', new.account_id using errcode = '23503';
  end if;
  if not (found_type = any (allowed)) then
    raise exception 'account % is %, expected one of %', new.account_id, found_type, allowed using errcode = '23514';
  end if;
  return new;
end;
$$;

