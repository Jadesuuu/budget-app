create function public.build_installment_schedule()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  each_amount bigint := new.total_centavos / new.installments;
begin
  if tg_op = 'UPDATE' then
    if (new.total_centavos, new.installments, new.frequency, new.first_due_date)
       is not distinct from (old.total_centavos, old.installments, old.frequency, old.first_due_date) then
      return new;
    end if;
    if exists (select 1 from public.installment_payments p where p.plan_id = new.id and p.paid_at is not null) then
      raise exception 'installment terms cannot change after a payment is recorded' using errcode = '23514';
    end if;
    delete from public.installment_payments p where p.plan_id = new.id;
  end if;

  for k in 1..new.installments loop
    insert into public.installment_payments (user_id, plan_id, seq, due_date, amount_centavos)
    values (
      new.user_id, new.id, k,
      case new.frequency
        when 'monthly' then (new.first_due_date + make_interval(months => k - 1))::date
        else new.first_due_date + 14 * (k - 1)
      end,
      -- leftover centavos go on the first payment
      case when k = 1 then new.total_centavos - each_amount * (new.installments - 1) else each_amount end
    );
  end loop;
  return new;
end;
$$;

create trigger installment_plans_build_schedule after insert or update on public.installment_plans
  for each row execute function public.build_installment_schedule();

